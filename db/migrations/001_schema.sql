-- Ice HR schema. Four tables, kept deliberately small so every row and rule is easy to reason about.
--
--   jobs            job titles with a salary range (reference data, read-only through the API)
--   departments     company departments; each may have a manager (an employee)
--   employees       people; each has a job, a department and (except the CEO) a manager
--   leave_requests  time off requested by an employee, approved or rejected by their manager
--
-- Seeded rows have ids 1 to 999. Rows created through the API or SQL get ids from 1001 up,
-- so a test can always tell seed data from data it created.

CREATE TABLE jobs (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title       VARCHAR(60)  NOT NULL,
  min_salary  INTEGER      NOT NULL,
  max_salary  INTEGER      NOT NULL,
  CONSTRAINT jobs_title_unique UNIQUE (title),
  CONSTRAINT jobs_min_salary_positive CHECK (min_salary > 0),
  CONSTRAINT jobs_salary_range_valid CHECK (max_salary >= min_salary)
);

CREATE TABLE departments (
  id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR(50)  NOT NULL,
  code        VARCHAR(5)   NOT NULL,
  location    VARCHAR(100) NOT NULL,
  manager_id  INTEGER,     -- foreign key added below, once employees exists
  created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT departments_code_unique UNIQUE (code),
  CONSTRAINT departments_code_format CHECK (code ~ '^[A-Z]{2,5}$')
);
-- Names are unique ignoring case: "Finance" and "FINANCE" cannot both exist.
CREATE UNIQUE INDEX departments_name_unique ON departments (lower(name));

CREATE TABLE employees (
  id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name        VARCHAR(50)  NOT NULL,
  last_name         VARCHAR(50)  NOT NULL,
  email             VARCHAR(100) NOT NULL,
  phone             VARCHAR(12),
  date_of_birth     DATE         NOT NULL,
  hire_date         DATE         NOT NULL,
  job_id            INTEGER      NOT NULL REFERENCES jobs (id),
  department_id     INTEGER      NOT NULL REFERENCES departments (id) ON DELETE RESTRICT,
  manager_id        INTEGER      REFERENCES employees (id) ON DELETE RESTRICT,
  salary            INTEGER      NOT NULL,
  status            VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
  termination_date  DATE,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT employees_email_unique UNIQUE (email),
  CONSTRAINT employees_email_lowercase CHECK (email = lower(email)),
  CONSTRAINT employees_phone_format CHECK (phone IS NULL OR phone ~ '^\d{3}-\d{3}-\d{4}$'),
  CONSTRAINT employees_salary_positive CHECK (salary > 0),
  CONSTRAINT employees_status_valid CHECK (status IN ('ACTIVE', 'TERMINATED')),
  CONSTRAINT employees_termination_date_matches_status
    CHECK ((status = 'TERMINATED') = (termination_date IS NOT NULL)),
  CONSTRAINT employees_not_own_manager CHECK (manager_id IS NULL OR manager_id <> id),
  CONSTRAINT employees_hired_after_birth CHECK (hire_date > date_of_birth)
);
CREATE INDEX employees_department_idx ON employees (department_id);
CREATE INDEX employees_manager_idx ON employees (manager_id);

ALTER TABLE departments
  ADD CONSTRAINT departments_manager_fk FOREIGN KEY (manager_id) REFERENCES employees (id) ON DELETE SET NULL;

CREATE TABLE leave_requests (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id      INTEGER      NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
  type             VARCHAR(10)  NOT NULL,
  start_date       DATE         NOT NULL,
  end_date         DATE         NOT NULL,
  days             INTEGER      NOT NULL,
  reason           VARCHAR(200),
  status           VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
  approver_id      INTEGER      REFERENCES employees (id) ON DELETE SET NULL,
  decision_reason  VARCHAR(200),
  decided_at       TIMESTAMPTZ,
  created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT leave_type_valid CHECK (type IN ('VACATION', 'SICK', 'PERSONAL')),
  CONSTRAINT leave_status_valid CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
  CONSTRAINT leave_dates_in_order CHECK (end_date >= start_date),
  CONSTRAINT leave_days_positive CHECK (days > 0)
);
CREATE INDEX leave_requests_employee_idx ON leave_requests (employee_id);
